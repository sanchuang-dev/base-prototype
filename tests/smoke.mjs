import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: {width:390,height:844}, deviceScaleFactor:1 });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
// The visual concept uses external photos; interaction smoke is deterministic without image network.
await page.route('**/lh3.googleusercontent.com/**', route => route.abort());
await page.goto('http://127.0.0.1:8765/#/home', { waitUntil:'domcontentloaded' });
assert.equal(await page.locator('[data-page].active').getAttribute('data-page'), 'home');
assert.equal(await page.locator('nav.tabbar .tab').count(), 5);
assert.match(await page.locator('.editorial-hero h2').innerText(), /以艾寄安/);
assert.equal(await page.locator('.collection-tile').count(), 2);
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2), true, 'mobile viewport must not overflow');

await page.locator('nav .tab[data-go="culture"]').click();
assert.equal(await page.locator('[data-page].active').getAttribute('data-page'), 'culture');
assert.match(await page.locator('.culture-editorial h3').innerText(), /艾草/);
assert.equal(await page.locator('[data-page="culture"] [data-action="read"]').count(), 0, 'culture should not be gamified');

await page.locator('nav .tab[data-go="shop"]').click();
assert.equal(await page.locator('[data-page].active').getAttribute('data-page'), 'shop');
assert.equal(await page.locator('[data-page="shop"] .shop-hero').isVisible(), true);
assert.equal(await page.locator('[data-page="shop"] [data-gift-collection]:visible').count(), 2);
await page.locator('[data-line-filter="seasonal"]').click();
assert.equal(await page.locator('[data-page="shop"] [data-gift-collection="seasonal"]:visible').count(),2);
assert.equal(await page.locator('[data-page="shop"] [data-gift-collection="premium"]:visible').count(),0);
assert.equal(await page.locator('.shop-seasonal-feature').isVisible(), true);
await page.locator('[data-line-filter="premium"]').click();
assert.equal(await page.locator('.shop-hero').isVisible(), true);
await page.locator('[data-page="shop"] [data-action="add"]').first().click();
await page.locator('[data-page="shop"] [data-action="favorite"]').first().click();
await page.locator('[data-page="shop"] [data-action="cart"]').click();
assert.match(await page.locator('#modal-title').innerText(),/心愿清单/);
await page.locator('#dialog button.close').click();

await page.locator('nav .tab[data-go="account"]').click();
assert.equal(await page.locator('[data-page].active').getAttribute('data-page'), 'account');
assert.equal(await page.locator('#account-wish-count').innerText(), '1');
assert.equal(await page.locator('#account-fav-count').innerText(), '1');
assert.match(await page.locator('#member-state').innerText(), /未进入/);
await page.locator('#member-cta').click();
assert.match(await page.locator('#member-state').innerText(), /演示会员/);
await page.locator('.account-actions [data-action="edit-profile"]').click();
await page.locator('#member-alias').fill('端阳小友');
await page.locator('#member-profile-form button[type="submit"]').click();
assert.equal(await page.locator('#member-name').innerText(), '端阳小友');
await page.locator('[data-page="account"] [data-action="demo-region"]').click();
await page.locator('[data-demo-region="韶关"]').click();
assert.match(await page.locator('#member-region').innerText(), /韶关/);
await page.reload({waitUntil:'domcontentloaded'});
assert.equal(await page.locator('[data-page].active').getAttribute('data-page'),'account');
assert.equal(await page.locator('#member-name').innerText(),'端阳小友');
assert.equal(await page.locator('#account-wish-count').innerText(),'1');
assert.equal(await page.locator('#account-fav-count').innerText(),'1');
assert.match(await page.locator('#member-region').innerText(), /韶关/);
await page.locator('.account-actions [data-action="show-favorites"]').click();
assert.match(await page.locator('#modal-title').innerText(), /我的收藏/);
await page.locator('#dialog button.close').click();
await page.locator('.account-actions [data-action="show-orders"]').click();
assert.match(await page.locator('#modal-body').innerText(), /暂无礼赠订单/);
await page.locator('#dialog button.close').click();
await page.locator('[data-page="account"] [data-action="demo-settings"]').click();
await page.locator('#dialog [data-action="demo-logout"]').click();
assert.match(await page.locator('#member-state').innerText(), /未进入/);
await page.locator('[data-page="account"] [data-action="demo-settings"]').click();
await page.locator('#dialog [data-action="clear-demo"]').click();
await page.locator('#dialog [data-action="confirm-clear-demo"]').click();
assert.equal(await page.locator('#account-wish-count').innerText(),'0');
assert.equal(await page.locator('#account-fav-count').innerText(),'0');
await page.reload({waitUntil:'domcontentloaded'});
assert.equal(await page.locator('#account-wish-count').innerText(),'0');
assert.match(await page.locator('#member-state').innerText(), /未进入/);

await page.locator('nav .tab[data-go="bespoke"]').click();
await page.locator('[data-quantity="1000"]').click();
const premiumPrice = Number((await page.locator('#price-unit').innerText()).replace(/[^\d]/g,''));
await page.locator('[data-gift-tier="seasonal"]').click();
const seasonalPrice = Number((await page.locator('#price-unit').innerText()).replace(/[^\d]/g,''));
assert.ok(seasonalPrice < premiumPrice, 'seasonal price must be below signature line');
await page.locator('[data-action="quote"]').click();
assert.match(await page.locator('#modal-body').innerText(),/节令安康礼/);
await page.locator('#dialog button.close').click();
await page.locator('#company').fill('原型测试机构');
await page.locator('#contact').fill('测试人');
await page.locator('#phone').fill('13800138000');
await page.locator('#inquiry button[type="submit"]').click();
assert.match(await page.locator('#modal-body').innerText(),/没有发送/);
await page.locator('#dialog button.close').click();

await page.locator('nav .tab[data-go="home"]').click();
await page.locator('[data-page="home"] [data-go="partners"]').click();
assert.equal(await page.locator('[data-page].active').getAttribute('data-page'), 'partners');
assert.equal(await page.locator('[data-page="partners"] .leaderboard').count(),0,'no fake partner rankings');
await page.locator('[data-page="partners"] .back-link').click();
assert.equal(await page.locator('[data-page].active').getAttribute('data-page'), 'home');
assert.deepEqual(errors,[]);
await page.screenshot({path:'mobile-smoke.png',fullPage:true});

const desktop = await browser.newPage({viewport:{width:1440,height:940},deviceScaleFactor:1});
desktop.on('pageerror',e=>errors.push(e.message));
await desktop.route('**/lh3.googleusercontent.com/**', route=>route.abort());
await desktop.goto('http://127.0.0.1:8765/#/home',{waitUntil:'domcontentloaded'});
assert.equal(await desktop.locator('.showcase').isVisible(),true);
assert.equal(await desktop.locator('.collection-tile').count(),2);
await desktop.screenshot({path:'desktop-smoke.png',fullPage:true});
assert.deepEqual(errors,[]);
console.log('Brand + member smoke passed: five tabs, two gift lines, demo login/profile, favorite, local persistence, logout, clear, quotes and collaboration');
await browser.close();
